-- 查询统计信息
SELECT 
    CASE status
        WHEN 0 THEN '待审批'
        WHEN 1 THEN '已通过'
        WHEN 2 THEN '已拒绝'
        WHEN 3 THEN '已取消'
        WHEN 4 THEN '已预约'
        WHEN 5 THEN '已完成'
    END AS '状态',
    COUNT(*) AS '数量'
FROM application
GROUP BY status
ORDER BY status;

-- 显示所有数据
SELECT id, real_name, phone, reason, DATE_FORMAT(appointment_time, '%Y-%m-%d %H:%i') AS appointment_time,
    CASE status
        WHEN 0 THEN '待审批'
        WHEN 1 THEN '已通过'
        WHEN 2 THEN '已拒绝'
        WHEN 3 THEN '已取消'
        WHEN 4 THEN '已预约'
        WHEN 5 THEN '已完成'
    END AS status
FROM application
ORDER BY create_time DESC;

